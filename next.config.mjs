// Baseline security headers (spec 15.4). No external origins are used
// anywhere in the app (fonts are self-hosted via next/font, FullCalendar and
// all other assets are bundled), so the CSP can stay restricted to 'self'.
// script-src needs 'unsafe-inline' for Next's own hydration bootstrap data
// and style-src needs it for FullCalendar's runtime-injected <style> tags -
// both are standard, low-risk allowances distinct from allowing inline
// *event handlers* or externally-loaded script/style origins, which this
// policy still blocks. A stricter nonce-based policy would need
// middleware.js to mint a per-request nonce; not justified yet for an
// internal-only tool with no user-generated HTML rendering.
const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self' data:",
  "connect-src 'self'",
  "frame-ancestors 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const SECURITY_HEADERS = [
  { key: "Content-Security-Policy", value: CONTENT_SECURITY_POLICY },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=()" },
  { key: "Strict-Transport-Security", value: "max-age=63072000; includeSubDomains" },
];

/** @type {import('next').NextConfig} */
const nextConfig = {
  /* config options here */
  experimental: {
    agentFeedback: true,
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: SECURITY_HEADERS,
      },
    ];
  },
};

export default nextConfig;
